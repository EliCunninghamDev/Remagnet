package dev.remagnet.app.data

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.security.KeyStore
import java.util.Base64
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/** Encrypt and decrypt a small string for storage. */
interface SecretCipher {
    fun encrypt(plaintext: String): String

    /** Return null when the ciphertext cannot be used with the current key. */
    fun decrypt(ciphertext: String): String?
}

/**
 * AES-256-GCM key held by the Android Keystore.
 *
 * The key bytes never enter the app process, and neither biometrics nor a PIN
 * are required, so background refreshes and QR imports keep working. This is
 * the same threat model as the extension's non-extractable WebCrypto key: code
 * running as the app can decrypt while the device is unlocked, but a copy of
 * SharedPreferences cannot.
 */
class KeystoreSecretCipher(
    private val alias: String = DEFAULT_ALIAS,
) : SecretCipher {
    private val keyStore: KeyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply {
        load(null)
    }

    override fun encrypt(plaintext: String): String {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, key())
        val encrypted = cipher.doFinal(plaintext.toByteArray(Charsets.UTF_8))
        // The IV is generated by the cipher and needed for decryption. Prefixing
        // it keeps the stored value to one string with no extra bookkeeping.
        val packed = cipher.iv + encrypted
        return Base64.getEncoder().encodeToString(packed)
    }

    override fun decrypt(ciphertext: String): String? = try {
        val packed = Base64.getDecoder().decode(ciphertext)
        require(packed.size > IV_BYTES)
        val iv = packed.copyOfRange(0, IV_BYTES)
        val body = packed.copyOfRange(IV_BYTES, packed.size)
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, key(), GCMParameterSpec(TAG_BITS, iv))
        String(cipher.doFinal(body), Charsets.UTF_8)
    } catch (_: Exception) {
        // A cleared Keystore, restored backup or truncated value leaves
        // ciphertext we cannot read. Treat it as absent so the user can replace
        // the secret instead of being locked out of settings.
        null
    }

    @Synchronized
    private fun key(): SecretKey {
        val existing = keyStore.getKey(alias, null) as? SecretKey
        if (existing != null) return existing

        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE)
        generator.init(
            KeyGenParameterSpec.Builder(
                alias,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(256)
                .build(),
        )
        return generator.generateKey()
    }

    private companion object {
        const val ANDROID_KEYSTORE = "AndroidKeyStore"
        const val DEFAULT_ALIAS = "remagnet.secrets.v1"
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val IV_BYTES = 12
        const val TAG_BITS = 128
    }
}
